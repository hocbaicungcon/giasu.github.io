"""Generate src/tables.js from core/mtef.py and core/omml.py so the JS port uses byte-identical tables (read-only import)."""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root))
from core import mtef, omml
R = mtef.Renderer
t = {
    'SPACE_TOKENS': sorted(mtef.SPACE_TOKENS), 'BINARY': sorted(mtef.BINARY), 'TALL': list(mtef.TALL),
    'FUNCTIONS': sorted(mtef.FUNCTIONS), 'FUNCTION_ALIASES': mtef.FUNCTION_ALIASES,
    'SYMBOLS': {str(k): v for k, v in mtef.SYMBOLS.items()},
    'GREEK_LOWER': mtef.GREEK_LOWER, 'GREEK_UPPER': mtef.GREEK_UPPER,
    'ASCII_ESCAPES': mtef.ASCII_ESCAPES, 'SPACES': {str(k): v for k, v in mtef.SPACES.items()},
    'FENCES': {str(k): v for k, v in mtef.FENCES.items()}, 'BIG_OPS': {str(k): v for k, v in mtef.BIG_OPS.items()},
    'TEXT_ESCAPES': mtef.TEXT_ESCAPES, 'EMBELLISHMENTS': {str(k): v for k, v in R.EMBELLISHMENTS.items()},
    'NARY': omml.NARY, 'ACCENTS': omml.ACCENTS, 'FENCE_CHARS': omml.FENCE_CHARS, 'OMML_ESCAPES': omml.ESCAPES,
}
out = pathlib.Path(__file__).resolve().parents[1] / 'src' / 'tables.js'
out.write_text('// generated by tools/gen_tables.py - do not edit\nexport default ' + json.dumps(t, ensure_ascii=True, indent=0) + ';\n', encoding='utf-8')
print('wrote', out, len(out.read_text()))
