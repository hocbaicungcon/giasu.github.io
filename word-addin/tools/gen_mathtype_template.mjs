// Extract the constant parts of a real MathType (DSMT) object so the writer can reproduce them:
// the three small OLE streams, one complete OLE file (directory layout), the Equation Native header and the MTEF prefixes
// (fonts + preferences) of the two common styles. Output: src/mathtype-template.js (generated, ~6 KB).
import { writeFileSync } from 'node:fs';
import { readZip } from '../tests/zip.js';
import { corpusFiles } from '../tests/corpus.js';
import { readOleStream, mtefFromOle, oleToLatex, Parser } from '../src/mtef.js';

const b64 = (d) => Buffer.from(d).toString('base64');
const found = {};
for (const f of corpusFiles()) {
  let z; try { z = readZip(f); } catch { continue; }
  for (const n of z.names.filter((x) => /embeddings\/oleObject\d+\.bin$/.test(x))) {
    const ole = new Uint8Array(z.read(n));
    let latex; try { latex = oleToLatex(ole)[0]; } catch { continue; }
    if (latex !== 'x') continue;
    const st = readOleStream(ole);
    const m = mtefFromOle(ole);
    const root = new Parser(m).parse()[0];
    const prefix = m.subarray(0, root.span[0]);
    const text = Buffer.from(prefix).toString('latin1');
    const style = text.includes('Palatino') ? 'palatino' : text.includes('Times New Roman') ? 'times' : null;
    if (!style || found[style] || prefix[11] !== 0x44 && prefix[10] !== 0x44) { /* keep scanning */ }
    if (style && !found[style] && ole.length < 4000 && !text.includes('TeX Input')) {
      found[style] = { prefix: b64(prefix), header: b64(st.subarray(0, 28)), ole: b64(ole) };
    }
  }
  if (found.palatino && found.times) break;
}
const any = found.times || found.palatino;
const streams = {};
const oleBytes = new Uint8Array(Buffer.from(any.ole, 'base64'));
for (const name of ['\u0001Ole', '\u0001CompObj', '\u0003ObjInfo']) streams[name] = b64(readOleStream(oleBytes, name));
const js = `// generated by tools/gen_mathtype_template.mjs - constant parts of a MathType (DSMT) OLE object\nexport const STYLES = ${JSON.stringify({ times: found.times && { prefix: found.times.prefix, header: found.times.header }, palatino: found.palatino && { prefix: found.palatino.prefix, header: found.palatino.header } })};\nexport const STREAMS = ${JSON.stringify(streams)};\nexport const TEMPLATE_OLE = ${JSON.stringify(any.ole)};\n`;
writeFileSync(new URL('../src/mathtype-template.js', import.meta.url), js);
console.log('styles', Object.keys(found), 'bytes', js.length);
