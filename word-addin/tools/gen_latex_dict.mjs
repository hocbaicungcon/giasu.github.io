// Build src/latex-dict.js from the TexCraft app's autocomplete dictionary (web/latex-complete.js, read only):
// formula commands, symbols, math environments and the Vietnamese aliases. Usage: node tools/gen_latex_dict.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../../web/latex-complete.js', import.meta.url), 'utf8');
const grab = (name) => {
  const start = src.indexOf(`const ${name} = `);
  let i = src.indexOf(/\[|\{/.exec(src.slice(start + name.length + 9))[0], start), depth = 0, end = i;
  const open = src[i], close = open === '[' ? ']' : '}';
  for (; end < src.length; end++) {
    const c = src[end];
    if (c === '"' || c === "'") { const q = c; end++; while (src[end] !== q) { if (src[end] === '\\') end++; end++; } continue; }
    if (c === open) depth++; else if (c === close && --depth === 0) break;
  }
  return new Function('return ' + src.slice(i, end + 1))();
};
const ENTRIES = grab('ENTRIES'), ALIASES = grab('CMD_ALIASES'), TERMS = grab('VI_MATH_TERMS');
const keepEnv = /^\\begin\{(cases|matrix|pmatrix|bmatrix|vmatrix|Vmatrix|aligned|array)\}$/;
const keepFormat = /^\\(text|mathrm|mathbf|mathbb|mathcal|mathit|mathsf|boldsymbol|operatorname)$/;
const entries = ENTRIES.filter(([cmd, , , cat]) => cat === 'math' || cat === 'symbol' || (cat === 'env' && keepEnv.test(cmd)) || (cat === 'format' && keepFormat.test(cmd)));
// extras a formula editor needs that the document-oriented list lacks
const extra = [
  ['\\xrightarrow', '\\xrightarrow{|}', 'Mũi tên có chữ trên \\xrightarrow', 'math'],
  ['\\xleftarrow', '\\xleftarrow{|}', 'Mũi tên trái có chữ \\xleftarrow', 'math'],
  ['\\overset', '\\overset{|}{}', 'Chữ trên ký hiệu \\overset', 'math'],
  ['\\underset', '\\underset{|}{}', 'Chữ dưới ký hiệu \\underset', 'math'],
  ['\\overbrace', '\\overbrace{|}^{}', 'Ngoặc nhọn trên \\overbrace', 'math'],
  ['\\underbrace', '\\underbrace{|}_{}', 'Ngoặc nhọn dưới \\underbrace', 'math'],
  ['\\boxed', '\\boxed{|}', 'Khung chữ nhật \\boxed', 'math'],
  ['\\operatorname', '\\operatorname{|}', 'Tên hàm tuỳ ý \\operatorname', 'format'],
  ['\\begin{array}', '\\begin{array}{c}\n  |\n\\end{array}', 'Bảng/ hệ array', 'env'],
  ['\\sin', '\\sin ', 'Hàm sin', 'math'], ['\\cos', '\\cos ', 'Hàm cos', 'math'], ['\\tan', '\\tan ', 'Hàm tan', 'math'], ['\\cot', '\\cot ', 'Hàm cot', 'math'],
  ['\\ln', '\\ln ', 'Logarit tự nhiên \\ln', 'math'], ['\\log', '\\log_{|}', 'Logarit \\log', 'math'], ['\\lg', '\\lg ', 'Logarit thập phân \\lg', 'math'],
  ['\\max', '\\max_{|}', 'Giá trị lớn nhất \\max', 'math'], ['\\min', '\\min_{|}', 'Giá trị nhỏ nhất \\min', 'math'],
  ['\\infty', '\\infty', 'Vô cực \\infty', 'symbol'], ['\\leq', '\\leq ', 'Nhỏ hơn hoặc bằng \\leq', 'symbol'], ['\\geq', '\\geq ', 'Lớn hơn hoặc bằng \\geq', 'symbol'],
  ['\\Rightarrow', '\\Rightarrow ', 'Suy ra \\Rightarrow', 'symbol'], ['\\Leftrightarrow', '\\Leftrightarrow ', 'Tương đương \\Leftrightarrow', 'symbol'],
  ['\\forall', '\\forall ', 'Với mọi \\forall', 'symbol'], ['\\exists', '\\exists ', 'Tồn tại \\exists', 'symbol'], ['\\in', '\\in ', 'Thuộc \\in', 'symbol'],
  ['\\cup', '\\cup ', 'Hợp \\cup', 'symbol'], ['\\cap', '\\cap ', 'Giao \\cap', 'symbol'], ['\\angle', '\\angle ', 'Góc \\angle', 'symbol'], ['\\perp', '\\perp ', 'Vuông góc \\perp', 'symbol'], ['\\parallel', '\\parallel ', 'Song song \\parallel', 'symbol'],
  ['\\circ', '^{\\circ}', 'Độ (°) ^{\\circ}', 'symbol'],
];
const seen = new Set(entries.map((e) => e[0]));
for (const e of extra) if (!seen.has(e[0])) { entries.push(e); seen.add(e[0]); }
const aliases = Object.fromEntries(Object.entries(ALIASES).filter(([k]) => seen.has('\\' + k) || seen.has(`\\begin{${k}}`)));
writeFileSync(new URL('../src/latex-dict.js', import.meta.url), `// generated by tools/gen_latex_dict.mjs from web/latex-complete.js - do not edit\nexport const ENTRIES = ${JSON.stringify(entries)};\nexport const ALIASES = ${JSON.stringify(aliases)};\nexport const TERMS = ${JSON.stringify(TERMS)};\n`);
console.log('entries', entries.length, 'aliases', Object.keys(aliases).length);
