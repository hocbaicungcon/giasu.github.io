// Learn how MathType really encodes each character (typeface + 8-bit fallback) from the corpus, so the MTEF writer
// produces what MathType itself writes. Output: src/mtefchars.js (generated). Usage: node tools/gen_mtef_chars.mjs
import { writeFileSync } from 'node:fs';
import { readZip } from '../tests/zip.js';
import { corpusFiles } from '../tests/corpus.js';
import { mtefFromOle, oleToLatex, Parser } from '../src/mtef.js';

const stats = new Map();   // codepoint -> Map("face|c8|opt" -> count)
const spaces = new Map();
const walk = (nd, parentTmpl) => {
  if (nd[0] === 'char') {
    const face = nd[1], code = nd[2] ?? nd[4] ?? nd[3];
    if (face === 24) { spaces.set(code, (spaces.get(code) || 0) + 1); return; }
    if (face === 22 || face === 23 || nd[5].length) return;   // fence pieces, markers, embellished letters are handled by templates
    const key = `${face}|${nd[3] === null ? '' : nd[3]}|${nd[2] === null ? 'nocode' : ''}`;
    const m = stats.get(code) || new Map();
    m.set(key, (m.get(key) || 0) + 1);
    stats.set(code, m);
  } else if (nd[0] === 'tmpl') nd[3].forEach((c) => walk(c));
  else if (nd[0] === 'line') nd[1].forEach((c) => walk(c));
  else if (nd[0] === 'pile') nd[2].forEach((c) => walk(c));
  else if (nd[0] === 'matrix') nd[3].forEach((c) => walk(c));
};
for (const f of corpusFiles()) {
  let z; try { z = readZip(f); } catch { continue; }
  for (const n of z.names.filter((x) => /embeddings\/oleObject\d+\.bin$/.test(x))) {
    const ole = new Uint8Array(z.read(n)); let m;
    try { oleToLatex(ole); m = mtefFromOle(ole); } catch { continue; }
    try { const [root] = new Parser(m).parse(); walk(root); } catch { /* ignore */ }
  }
}
const out = {};
for (const [cp, m] of stats) {
  const ranked = [...m.entries()].sort((a, b) => b[1] - a[1]);
  const total = ranked.reduce((s, x) => s + x[1], 0);
  if (total < 3) continue;
  const [face, c8] = ranked[0][0].split('|');
  out[cp] = { face: Number(face), c8: c8 === '' ? null : Number(c8), n: total, share: Math.round(ranked[0][1] / total * 100) };
}
const sp = Object.fromEntries([...spaces.entries()].sort((a, b) => b[1] - a[1]));
writeFileSync(new URL('../src/mtefchars.js', import.meta.url), `// generated by tools/gen_mtef_chars.mjs - do not edit\nexport const CHARS = ${JSON.stringify(out)};\nexport const SPACE_CODES = ${JSON.stringify(sp)};\n`);
console.log('chars', Object.keys(out).length, 'space codes', JSON.stringify(sp));
